-- Meta Ads (Fase 2): conexión por organización y snapshots diarios de resultados.
-- Solo lectura (ads_read). Todo el acceso pasa por RLS con org_id.

-- ---------- meta_ads_conexiones ----------
CREATE TABLE IF NOT EXISTS meta_ads_conexiones (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id                  BIGINT NOT NULL DEFAULT NULLIF(current_setting('app.current_org', true), '')::bigint REFERENCES orgs(id) ON DELETE CASCADE,
  ad_account_id           TEXT NOT NULL,
  access_token_encrypted  TEXT NOT NULL,
  refresh_token_encrypted TEXT,
  token_expira_at         TIMESTAMPTZ(6),
  estado                  TEXT NOT NULL DEFAULT 'activa',
  ultimo_error            TEXT,
  sincronizado_at         TIMESTAMPTZ(6),
  sincronizando_at        TIMESTAMPTZ(6),
  created_at              TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS meta_ads_conexiones_org_uq ON meta_ads_conexiones(org_id);
CREATE INDEX IF NOT EXISTS meta_ads_conexiones_org_estado_idx ON meta_ads_conexiones(org_id, estado);

-- ---------- meta_ads_insights ----------
CREATE TABLE IF NOT EXISTS meta_ads_insights (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         BIGINT NOT NULL DEFAULT NULLIF(current_setting('app.current_org', true), '')::bigint REFERENCES orgs(id) ON DELETE CASCADE,
  ad_id          TEXT NOT NULL,
  nombre_anuncio TEXT NOT NULL,
  fecha          DATE NOT NULL,
  spend          DECIMAL(12, 2) NOT NULL DEFAULT 0,
  ctr            DECIMAL(8, 4) NOT NULL DEFAULT 0,
  cpa            DECIMAL(12, 2) NOT NULL DEFAULT 0,
  impresiones    INTEGER NOT NULL DEFAULT 0,
  created_at     TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS meta_ads_insights_org_ad_fecha_uq ON meta_ads_insights(org_id, ad_id, fecha);
CREATE INDEX IF NOT EXISTS meta_ads_insights_org_fecha_idx ON meta_ads_insights(org_id, fecha);

-- ---------- RLS + permisos ----------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['meta_ads_conexiones','meta_ads_insights'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS org_isolation ON %I', t);
    EXECUTE format('CREATE POLICY org_isolation ON %I USING (org_id = NULLIF(current_setting(''app.current_org'', true), '''')::bigint) WITH CHECK (org_id = NULLIF(current_setting(''app.current_org'', true), '''')::bigint)', t);
  END LOOP;
END $$;

GRANT SELECT, INSERT, UPDATE, DELETE ON meta_ads_conexiones,meta_ads_insights TO crm_app;
GRANT USAGE, SELECT ON SEQUENCE meta_ads_conexiones_id_seq,meta_ads_insights_id_seq TO crm_app;
