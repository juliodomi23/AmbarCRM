-- Meta Ads (Fase 2): snapshot agregado de gasto/resultados por hora del día.
-- Solo lectura (ads_read). Todo el acceso pasa por RLS con org_id.
-- Se reemplaza completo en cada sync: 24 filas (hora 0-23) por organización.

-- ---------- meta_ads_horarios ----------
CREATE TABLE IF NOT EXISTS meta_ads_horarios (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         BIGINT NOT NULL DEFAULT NULLIF(current_setting('app.current_org', true), '')::bigint REFERENCES orgs(id) ON DELETE CASCADE,
  hora           INTEGER NOT NULL,
  spend          DECIMAL(12, 2) NOT NULL DEFAULT 0,
  impresiones    INTEGER NOT NULL DEFAULT 0,
  resultados     INTEGER NOT NULL DEFAULT 0,
  created_at     TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(6) NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS meta_ads_horarios_org_hora_uq ON meta_ads_horarios(org_id, hora);
CREATE INDEX IF NOT EXISTS meta_ads_horarios_org_idx ON meta_ads_horarios(org_id);

-- ---------- RLS + permisos ----------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['meta_ads_horarios'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS org_isolation ON %I', t);
    EXECUTE format('CREATE POLICY org_isolation ON %I USING (org_id = NULLIF(current_setting(''app.current_org'', true), '''')::bigint) WITH CHECK (org_id = NULLIF(current_setting(''app.current_org'', true), '''')::bigint)', t);
  END LOOP;
END $$;

GRANT SELECT, INSERT, UPDATE, DELETE ON meta_ads_horarios TO crm_app;
GRANT USAGE, SELECT ON SEQUENCE meta_ads_horarios_id_seq TO crm_app;
